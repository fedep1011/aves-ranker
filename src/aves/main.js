      loadImgForCanvas(url) {
        if (!url) return Promise.resolve(null);
        if (this.state.imageCache.has(url)) return Promise.resolve(this.state.imageCache.get(url));

        const loadFromBlobUrl = (blobUrl, cacheKey) =>
          new Promise(resolve => {
            const img = new Image();
            img.onload = () => {
              this.state.imageCache.set(cacheKey, img);
              resolve(img);
            };
            img.onerror = () => resolve(null);
            img.src = blobUrl;
          });

        const loadWithCorsTag = (srcUrl, cacheKey) =>
          new Promise(resolve => {
            const img = new Image();
            img.crossOrigin = "anonymous";
            img.onload = () => {
              this.state.imageCache.set(cacheKey, img);
              resolve(img);
            };
            img.onerror = () => resolve(null);
            img.src = srcUrl;
          });

        return (async () => {
          try {
            const res = await fetch(url, { mode: "cors", cache: "reload" });
            if (res.ok) {
              const blob = await res.blob();
              const objUrl = URL.createObjectURL(blob);
              const loaded = await loadFromBlobUrl(objUrl, url);
              if (loaded) return loaded;
            }
          } catch (_) {}

          try {
            const proxyUrl = `https://wsrv.nl/?url=${encodeURIComponent(url)}&output=jpg`;
            const resProxy = await fetch(proxyUrl, { mode: "cors" });
            if (resProxy.ok) {
              const blob = await resProxy.blob();
              const objUrl = URL.createObjectURL(blob);
              const loaded = await loadFromBlobUrl(objUrl, url);
              if (loaded) return loaded;
            }
          } catch (_) {}

          const sep = url.includes("?") ? "&" : "?";
          return await loadWithCorsTag(`${url}${sep}canvas_cors=1`, url);
        })();
      },

      drawCompleteBirdPhoto(ctx, img, x, y, w, h) {
        ctx.save();
        const ir = img.width / img.height;
        const br = w / h;
        let sx = 0, sy = 0, sw = img.width, sh = img.height;
        if (ir > br) {
          sw = img.height * br;
          sx = (img.width - sw) / 2;
        } else {
          sh = img.width / br;
          sy = (img.height - sh) / 2;
        }
        try {
          ctx.filter = "blur(18px) brightness(0.68)";
        } catch (_) {}
        ctx.drawImage(img, sx, sy, sw, sh, x - 20, y - 20, w + 40, h + 40);
        ctx.restore();

        ctx.fillStyle = "rgba(18, 22, 19, 0.22)";
        ctx.fillRect(x, y, w, h);

        let dw = w, dh = h, dx = x, dy = y;
        if (ir > br) {
          dh = w / ir;
          dy = y + (h - dh) / 2;
        } else {
          dw = h * ir;
          dx = x + (w - dw) / 2;
        }
        ctx.drawImage(img, 0, 0, img.width, img.height, dx, dy, dw, dh);
      },

      wrapCanvasText(ctx, text, x, y, maxWidth, lineHeight, maxLines = 2) {
        const words = (text || "").split(" ");
        let line = "";
        let linesDrawn = 0;
        for (let n = 0; n < words.length; n++) {
          const testLine = line + words[n] + " ";
          const metrics = ctx.measureText(testLine);
          if (metrics.width > maxWidth && n > 0) {
            linesDrawn++;
            if (linesDrawn >= maxLines) {
              ctx.fillText(line.trim() + "...", x, y);
              return;
            }
            ctx.fillText(line.trim(), x, y);
            line = words[n] + " ";
            y += lineHeight;
          } else {
            line = testLine;
          }
        }
        if (line.trim()) {
          ctx.fillText(line.trim(), x, y);
        }
      },

