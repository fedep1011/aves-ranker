      async fetchWinnerBirdAudioUrl(bird) {
        if (!bird) return "";
        if (bird.audioUrl) return bird.audioUrl;

        const extractSoundFromObs = (results) => {
          for (const obs of (results || [])) {
            if (obs && Array.isArray(obs.sounds)) {
              for (const s of obs.sounds) {
                if (s && s.file_url && !s.file_url.endsWith(".wav")) {
                  return s.file_url;
                }
              }
              if (obs.sounds[0] && obs.sounds[0].file_url) {
                return obs.sounds[0].file_url;
              }
            }
          }
          return "";
        };

        try {
          const res = await fetch(`${CATALOG_DATA.baseUrl}/observations?taxon_id=${encodeURIComponent(bird.id)}&sounds=true&per_page=8&order_by=votes`);
          if (res.ok) {
            const data = await res.json();
            const found = extractSoundFromObs(data.results);
            if (found) {
              bird.audioUrl = found;
              return found;
            }
          }
        } catch (_) {}

        try {
          const genus = (bird.nombreCientifico || "").split(" ")[0];
          if (genus) {
            const resG = await fetch(`${CATALOG_DATA.baseUrl}/observations?q=${encodeURIComponent(genus)}&taxon_id=3&sounds=true&per_page=6`);
            if (resG.ok) {
              const dataG = await resG.json();
              const foundG = extractSoundFromObs(dataG.results);
              if (foundG) {
                bird.audioUrl = foundG;
                return foundG;
              }
            }
          }
        } catch (_) {}

        return "";
      },

      playSynthesizedBirdSongFallback(times = 1) {
        this.stopWinnerAudio();
        try {
          const AudioCtx = window.AudioContext || window.webkitAudioContext;
          if (!AudioCtx) return;
          const ctx = new AudioCtx();
          this.state.winnerAudioPlaying = true;
          this.state.winnerAudioPlayCount = 0;
          this.updateWinnerAudioUI();

          const playPhrase = (passIdx) => {
            if (!this.state.winnerAudioPlaying) return;
            this.state.winnerAudioPlayCount = passIdx;
            this.updateWinnerAudioUI();

            const notes = [
              { f1: 1760, f2: 2480, dur: 0.14, gap: 0.05 },
              { f1: 2100, f2: 2950, dur: 0.16, gap: 0.06 },
              { f1: 2640, f2: 1980, dur: 0.24, gap: 0.1 }
            ];
            let offset = ctx.currentTime + 0.04;
            notes.forEach(n => {
              const osc = ctx.createOscillator();
              const gain = ctx.createGain();
              osc.type = "sine";
              osc.frequency.setValueAtTime(n.f1, offset);
              osc.frequency.exponentialRampToValueAtTime(n.f2, offset + n.dur);

              gain.gain.setValueAtTime(0.001, offset);
              gain.gain.exponentialRampToValueAtTime(0.16, offset + 0.03);
              gain.gain.exponentialRampToValueAtTime(0.001, offset + n.dur);

              osc.connect(gain);
              gain.connect(ctx.destination);
              osc.start(offset);
              osc.stop(offset + n.dur + 0.01);
              offset += n.dur + n.gap;
            });
          };

          playPhrase(0);
          if (times > 1) {
            const t1 = setTimeout(() => playPhrase(1), 1100);
            const t2 = setTimeout(() => {
              this.state.winnerAudioPlaying = false;
              this.state.winnerAudioPlayCount = times;
              this.updateWinnerAudioUI();
            }, 2200);
            this.state.synthTimerIds.push(t1, t2);
          } else {
            const tEnd = setTimeout(() => {
              this.state.winnerAudioPlaying = false;
              this.state.winnerAudioPlayCount = 1;
              this.updateWinnerAudioUI();
            }, 1150);
            this.state.synthTimerIds.push(tEnd);
          }
        } catch (_) {
          this.state.winnerAudioPlaying = false;
          this.updateWinnerAudioUI();
        }
      },

      async resolveAndPlayWinnerAudio(winnerBird, maxPlays = 1) {
        this.stopWinnerAudio();
        if (!winnerBird) return;

        this.state.winnerAudioHasPlayed = true;
        this.state.winnerAudioMaxPlays = maxPlays;
        this.state.winnerAudioPlayCount = 0;

        const audioUrl = await this.fetchWinnerBirdAudioUrl(winnerBird);
        this.state.winnerAudioUrl = audioUrl;

        // Ensure user is still on Results screen after async fetch
        if (document.getElementById("viewResults").classList.contains("hidden")) return;

        if (!audioUrl) {
          this.playSynthesizedBirdSongFallback(maxPlays);
          return;
        }

        if (!this.state.winnerAudioEl) {
          this.state.winnerAudioEl = new Audio();
        }
        const audio = this.state.winnerAudioEl;
        audio.src = audioUrl;
        audio.volume = 0.85;
        this.state.winnerAudioPlaying = true;
        this.updateWinnerAudioUI();

        const playOnce = () => {
          if (!this.state.winnerAudioPlaying || document.getElementById("viewResults").classList.contains("hidden")) {
            this.stopWinnerAudio();
            return;
          }
          audio.currentTime = 0;
          const p = audio.play();
          if (p && typeof p.then === "function") {
            p.then(() => {
              this.updateWinnerAudioUI();
              const clipTimer = setTimeout(() => {
                if (this.state.winnerAudioPlaying && !audio.paused) {
                  audio.pause();
                  if (typeof audio.onended === "function") audio.onended();
                }
              }, 5500);
              this.state.synthTimerIds.push(clipTimer);
            }).catch(() => {
              this.state.winnerAudioPlaying = false;
              this.updateWinnerAudioUI();
            });
          }
        };

        audio.onended = () => {
          this.state.winnerAudioPlayCount++;
          if (this.state.winnerAudioPlayCount < this.state.winnerAudioMaxPlays && this.state.winnerAudioPlaying) {
            const gapTimer = setTimeout(() => playOnce(), 350);
            this.state.synthTimerIds.push(gapTimer);
          } else {
            this.state.winnerAudioPlaying = false;
            this.updateWinnerAudioUI();
          }
        };

        playOnce();
      },

